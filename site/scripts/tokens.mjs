// hibari の色のトークンを web/app/globals.css から抜き出し、サイトの CSS にする（ADR 0064 決定 3）。
//
// globals.css をそのまま読み込まないのは、hibari が Tailwind の既定のテーマを捨てているため（`--*: initial`）。
// そのまま読むと Fumadocs の部品の角丸や影が黙って消え、文字の大きさも hibari の段階に変わる（試作で確かめた）。
// 共有するのは色だけにし、値は書き写さずに毎回ここで抜き出す。`npm run dev` / `npm run build` の前に動く。
//
//   node scripts/tokens.mjs   # app/tokens.gen.css を書く

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * CSS の中の、`opener` で始まるブロックの直下（入れ子の中は見ない）にある `--color-*` の宣言を、書いてある順に返す。
 * @param {string} css
 * @param {string} opener ブロックの始まり（`@theme static` など）
 * @returns {[string, string][]}
 */
export function colorDeclarations(css, opener) {
  // 行の頭のセレクタだけを見る（globals.css の先頭のコメントにも `[data-theme="dark"]` の文字がある）
  const escaped = opener.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = new RegExp(`^${escaped}\\s*\\{`, "m").exec(css);
  if (!match) throw new Error(`${opener} is not found in globals.css`);
  const open = match.index + match[0].length - 1;
  let depth = 0;
  let body = "";
  for (let i = open; i < css.length; i++) {
    const c = css[i];
    if (c === "{") depth++;
    if (c === "}") depth--;
    if (depth === 0) break;
    // 入れ子のブロック（@keyframes など）の中身は読まない
    if (depth === 1 && i !== open) body += c;
  }
  const declarations = [];
  for (const m of body.matchAll(/(--color-[a-z0-9-]+)\s*:\s*([^;]+);/g)) declarations.push([m[1], m[2].trim()]);
  return declarations;
}

/**
 * @param {string} css globals.css の中身
 * @returns {string} ライトを :root に、ダークを [data-theme="dark"] に置いた CSS
 */
export function tokensCSS(css) {
  const block = (selector, declarations) =>
    `${selector} {\n${declarations.map(([name, value]) => `  ${name}: ${value};`).join("\n")}\n}\n`;
  return [
    "/* Code generated by site/scripts/tokens.mjs from web/app/globals.css. DO NOT EDIT. */\n",
    block(":root", colorDeclarations(css, "@theme static")),
    block('[data-theme="dark"]', colorDeclarations(css, '[data-theme="dark"]')),
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = readFileSync(new URL("../../web/app/globals.css", import.meta.url), "utf8");
  writeFileSync(new URL("../app/tokens.gen.css", import.meta.url), tokensCSS(css));
}
